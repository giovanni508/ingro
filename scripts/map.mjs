// Renders the stylised "Dove siamo" map from OpenStreetMap data (assets/map/osm-area.xml,
// © OpenStreetMap contributors, ODbL) into src/components/home/map-data.ts.
// Usage: node scripts/map.mjs
import fs from "node:fs";

const xml = fs.readFileSync("assets/map/osm-area.xml", "utf8");
const B = { minlon: 13.361, minlat: 38.0815, maxlon: 13.387, maxlat: 38.0975 };
const STORE = { lat: 38.0894474, lon: 13.3739767 };
const W = 1000;
const k = W / ((B.maxlon - B.minlon) * Math.cos((STORE.lat * Math.PI) / 180));
const H = Math.round((B.maxlat - B.minlat) * k);
const proj = (lat, lon) => [((lon - B.minlon) * Math.cos((STORE.lat * Math.PI) / 180)) * k, (B.maxlat - lat) * k];

const nodes = new Map();
for (const m of xml.matchAll(/<node id="(\d+)"[^>]*?lat="([\d.-]+)" lon="([\d.-]+)"/g)) nodes.set(m[1], [+m[2], +m[3]]);
const MAJOR = /^(motorway|trunk|primary|secondary|motorway_link|trunk_link|primary_link|secondary_link)$/;
const MID = /^(tertiary|tertiary_link)$/;
const MINOR = /^(unclassified|residential|living_street|pedestrian|service)$/;
const groups = { major: [], mid: [], minor: [], viale: [] };
for (const m of xml.matchAll(/<way id="\d+"[^>]*>([\s\S]*?)<\/way>/g)) {
  const body = m[1];
  const hw = body.match(/<tag k="highway" v="([^"]+)"/)?.[1];
  if (!hw) continue;
  const name = body.match(/<tag k="name" v="([^"]+)"/)?.[1] ?? "";
  if (hw === "service" && !/parking_aisle|driveway/.test(body) === false) continue;
  const pts = [...body.matchAll(/<nd ref="(\d+)"/g)].map((r) => nodes.get(r[1])).filter(Boolean).map(([la, lo]) => proj(la, lo));
  if (pts.length < 2) continue;
  const d = "M" + pts.map(([x, y]) => `${x.toFixed(1)} ${y.toFixed(1)}`).join("L");
  if (/Regione Siciliana/i.test(name)) groups.viale.push(d);
  else if (MAJOR.test(hw)) groups.major.push(d);
  else if (MID.test(hw)) groups.mid.push(d);
  else if (MINOR.test(hw) && hw !== "service") groups.minor.push(d);
}
const [sx, sy] = proj(STORE.lat, STORE.lon);
const ts = `// Generated by scripts/map.mjs from OpenStreetMap data (© OpenStreetMap contributors, ODbL). Do not edit.
export const MAP_VIEWBOX = "0 0 ${W} ${H}";
export const MAP_W = ${W};
export const MAP_H = ${H};
export const STORE_XY = [${sx.toFixed(1)}, ${sy.toFixed(1)}] as const;
export const ROADS = {
  minor: ${JSON.stringify(groups.minor.join(""))},
  mid: ${JSON.stringify(groups.mid.join(""))},
  major: ${JSON.stringify(groups.major.join(""))},
  viale: ${JSON.stringify(groups.viale.join(""))},
};
`;
fs.mkdirSync("src/components/home", { recursive: true });
fs.writeFileSync("src/components/home/map-data.ts", ts);
console.log(W, H, Object.fromEntries(Object.entries(groups).map(([a, b]) => [a, b.length])), (ts.length / 1024).toFixed(0) + "KB");
